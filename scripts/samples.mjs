// Print a Markdown table of sample conversions: each input to every other
// generation. Usage: npm run samples [-- output.md]
import { readFile, writeFile } from 'node:fs/promises';
import { createConverter, DICTIONARIES, GENERATION_IDS } from '../src/engine/index.js';
import { SEED_SAMPLES } from '../src/samples.js';
import { resolveSiteName } from '../src/config/site.js';

const siteConfig = JSON.parse(await readFile(new URL('../src/config/site.json', import.meta.url), 'utf8'));

const MIXED = [
  { from: 'millennial', text: "Lol I can't believe it. Honestly that party was hella lit, my squad was jelly LMAO" },
  { from: 'genz', text: 'ngl that fit slaps, bro is so pressed 💀💀 bet, gotta dip.\nno cap fr' },
];

const converter = createConverter({ mode: 'rules' });
/** @param {string} s */
const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, '<br>');

const lines = [
  `# ${resolveSiteName(siteConfig)}: sample conversions`,
  '',
  'Generated by `npm run samples` (scripts/samples.mjs). Each concept is written as the target\'s highest-weight entry.',
  '',
];
for (const { from, text } of [...SEED_SAMPLES, ...MIXED]) {
  lines.push(`## From ${DICTIONARIES[from].label}`, '', `> ${cell(text)}`, '', '| To | Output | Changes |', '|---|---|---|');
  for (const to of GENERATION_IDS.filter((g) => g !== from)) {
    const result = await converter.convert(text, { from, to });
    lines.push(`| ${DICTIONARIES[to].label} | ${cell(result.text)} | ${result.changes.length} |`);
  }
  lines.push('');
}

const markdown = lines.join('\n');
const outFile = process.argv[2];
if (outFile) {
  await writeFile(outFile, markdown);
  console.log(`wrote ${outFile}`);
} else {
  console.log(markdown);
}
